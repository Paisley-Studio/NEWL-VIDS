// Production checks — run before rendering or deploying (`npm run verify`).
// Exits non-zero with a list of problems; never "passes" on missing assets.
import fs from "node:fs";
import path from "node:path";

const problems = [];
const ok = [];
const fail = (m) => problems.push(m);
const exists = (p) => fs.existsSync(p);
const read = (p) => fs.readFileSync(p, "utf8");

/* ---------- lesson scripts → assets ---------- */
const sfxUsed = new Set(["click", "typing", "pop", "whoosh", "whoosh-soft", "riser", "impact", "shimmer"]);
const lessonFiles = fs.readdirSync("scripts/narration").filter((f) => /^lesson-\d+\.json$/.test(f)).sort();
if (lessonFiles.length !== 6) fail(`expected 6 lesson scripts, found ${lessonFiles.length}`);
const musicDur = exists("public/audio/music/durations.json") ? JSON.parse(read("public/audio/music/durations.json")) : {};
for (const f of lessonFiles) {
  const l = JSON.parse(read(path.join("scripts/narration", f)));
  const timingPath = `src/generated/${l.id}.timing.json`;
  const timing = exists(timingPath) ? JSON.parse(read(timingPath)) : { beats: {} };
  let beats = 0;
  for (const s of l.scenes) {
    const imgs = [s.image, ...s.beats.map((b) => b.image)].filter(Boolean);
    for (const im of imgs) if (!exists(`public/screenshots/${im}.png`)) fail(`${l.id}/${s.id}: screenshot ${im}.png missing`);
    s.beats.forEach((b, i) => {
      beats++;
      (b.sfx || []).forEach((x) => sfxUsed.add(x));
      const t = timing.beats[`${s.id}-${i}`];
      if (!t) fail(`${l.id}/${s.id}-${i}: no narration timing (run npm run narration)`);
      else if (!exists(path.join("public", t.file))) fail(`${l.id}/${s.id}-${i}: narration file ${t.file} missing`);
    });
  }
  if (!exists(`public/audio/music/${l.id}.mp3`)) fail(`${l.id}: music missing`);
  if (!musicDur[l.id]) fail(`${l.id}: music duration not recorded`);
  if (!l.scenes.length || l.scenes[l.scenes.length - 1].kind !== "credits") fail(`${l.id}: last scene must be the KEYPOLE TECHNOLOGIES credits`);
  ok.push(`${l.id}: ${l.scenes.length} scenes, ${beats} beats`);
}
for (const s of sfxUsed) if (!exists(`public/audio/sfx/${s}.wav`)) fail(`sound effect ${s}.wav missing`);
for (const p of ["public/branding/keypole-technologies-logo.png", "public/frame/dots.png", "public/fonts/inter-latin-400-normal.woff2"]) if (!exists(p)) fail(`${p} missing`);

/* ---------- generated site data ---------- */
if (!exists("data/lessons.json")) fail("data/lessons.json missing (run npm run export)");
else {
  const { lessons } = JSON.parse(read("data/lessons.json"));
  for (const l of lessons) {
    for (const p of [l.subtitles.vtt, l.subtitles.srt, l.script, l.script.replace(/\.md$/, ".html")]) if (!exists(p)) fail(`${l.id}: ${p} missing`);
    if (!l.narrationComplete) fail(`${l.id}: narration incomplete`);
    if (!(l.duration > 60)) fail(`${l.id}: implausible duration ${l.duration}`);
    l.chapters.forEach((c, i) => i && c.start <= l.chapters[i - 1].start && fail(`${l.id}: chapters not ascending`));
    // subtitle integrity
    if (exists(l.subtitles.vtt)) {
      const vtt = read(l.subtitles.vtt);
      if (!vtt.startsWith("WEBVTT")) fail(`${l.subtitles.vtt}: missing WEBVTT header`);
      const toS = (t) => t.split(":").reduce((a, v) => a * 60 + parseFloat(v), 0);
      let prevEnd = -1;
      for (const m of vtt.matchAll(/(\d\d:\d\d:\d\d\.\d{3}) --> (\d\d:\d\d:\d\d\.\d{3})/g)) {
        const a = toS(m[1]);
        const b = toS(m[2]);
        if (b <= a) fail(`${l.subtitles.vtt}: cue ends before it starts at ${m[1]}`);
        if (a < prevEnd - 0.001) fail(`${l.subtitles.vtt}: overlapping cue at ${m[1]}`);
        if (b > l.duration + 0.5) fail(`${l.subtitles.vtt}: cue beyond video end at ${m[1]}`);
        prevEnd = b;
      }
    }
  }
  ok.push(`data/lessons.json: ${lessons.length} lessons, ${Math.round(lessons.reduce((s, l) => s + l.duration, 0) / 60)} min`);
}

/* ---------- learning centre references ---------- */
const html = read("index.html");
for (const m of html.matchAll(/(?:src|href)="([^"#][^"]*)"/g)) {
  const ref = m[1];
  if (/^(https?:|mailto:|data:)/.test(ref)) continue;
  if (!exists(ref)) fail(`index.html references missing file ${ref}`);
}
ok.push("index.html local references resolve");

/* ---------- sensitive values must never be published ---------- */
// Generic patterns only — this file must not itself contain the values it guards against.
const SENSITIVE = [
  /[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev/i, // the real SMS Worker address
  /\bNLA-[A-Za-z0-9]{6}\b/, // passwords generated by genPassword()
  /AIzaSy[0-9A-Za-z_-]{20,}/, // Firebase / Google API keys
  /\b[A-Za-z0-9._%+-]+@newlafrica\.com\b/i, // staff e-mail addresses
  /(?<![\d+])(?:\+?254|0)7(?!12345678)\d{8}\b/, // Kenyan mobile numbers (except the app's placeholder 0712345678)
];
const scanDirs = ["index.html", "assets", "data", "resources", "subtitles", "scripts/narration", "src", "public/screenshots/index.json", "README.md"];
const walk = (p) => (fs.statSync(p).isDirectory() ? fs.readdirSync(p).flatMap((c) => walk(path.join(p, c))) : [p]);
for (const d of scanDirs) {
  if (!exists(d)) continue;
  for (const file of walk(d)) {
    if (!/\.(html|js|mjs|ts|tsx|json|md|css|vtt|srt|txt)$/.test(file)) continue;
    const text = read(file);
    for (const re of SENSITIVE) if (re.test(text)) fail(`sensitive value ${re} found in ${file}`);
  }
}
ok.push("no known credentials or personal identifiers in published files");

console.log(ok.map((m) => `✔ ${m}`).join("\n"));
if (problems.length) {
  console.error(`\n✖ ${problems.length} problem(s):\n` + problems.map((p) => `  - ${p}`).join("\n"));
  process.exit(1);
}
console.log("\nAll production checks passed.");
